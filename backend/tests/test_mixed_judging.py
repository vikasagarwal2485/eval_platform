def judgements(h, run_id):
    """result answer's model -> [(judge, outcome, value)]"""
    with h.sf() as s:
        run = repo.get_run(s, run_id)
        names = {sn.id: sn.name for sn in repo.run_snapshots(s, run)}
        att = repo.latest_attempt(s, run_id)
        res = {r.id: names[r.model_snapshot_id] for r in repo.list_results(s, run_id)}
        out: dict[str, list] = {}
        for j in repo.list_judgements(s, att.id):
            out.setdefault(res[j.result_id], []).append((j.judge_model, j.outcome, j.value))
    return out


def scores(h, run_id):
    with h.sf() as s:
        att = repo.latest_attempt(s, run_id)
        by = {r.id: r for r in repo.list_results(s, run_id)}
        names = {sn.id: sn.name for sn in repo.run_snapshots(s, repo.get_run(s, run_id))}
        return {
            names[by[x.result_id].model_snapshot_id]: x
            for x in repo.list_scores(s, run_id, att.id)
            if x.kind == "judge"
        }


def judge_requests(server):
    return [
        r
        for r in server.chat_requests()
        if "response_format" in (r["body"] or {}) or "tool_choice" in (r["body"] or {})
    ]


# ---------------------------------------------------------------- a hosted single judge
async def test_hosted_judge_over_local_models_is_not_a_contestant_or_self_judged(h):
    run_id = h.add_run(
        ["qwen3:8b", "gemma:test"], [GEN], judge_mode="single", judge_model=GPT, config={"warmup": False}
    )
    run = await h.run(run_id)
    assert run.status == "completed"
    sc = scores(h, run_id)
    assert {m: (x.outcome, x.value) for m, x in sc.items()} == {
        "qwen3:8b": ("judged", 1.0),
        "gemma:test": ("judged", 1.0),
    }
    assert all(x.detail["self_judged"] is False and x.detail["judge_model"] == GPT for x in sc.values())
    assert (
        len(judge_requests(h.oa)) == 2 and len(h.oa.chat_requests()) == 2
    )  # judging only; nothing generated by gpt-4o
    assert not [c for c in h.ollama.calls if c[0] == "chat" and c[4] is not None]  # local models judged nothing


async def test_a_hosted_judge_that_is_also_a_contestant_is_still_flagged_self_judged(h):
    run_id = h.add_run([GPT, "qwen3:8b"], [GEN], judge_mode="single", judge_model=GPT, config={"warmup": False})
    await h.run(run_id)
    sc = scores(h, run_id)
    assert sc[GPT].detail["self_judged"] is True and sc["qwen3:8b"].detail["self_judged"] is False


async def test_openai_judge_requests_use_strict_json_schema_output(h):
    run_id = h.add_run(["qwen3:8b"], [GEN], judge_mode="single", judge_model=GPT, config={"warmup": False})
    await h.run(run_id)
    (req,) = judge_requests(h.oa)
    rf = req["body"]["response_format"]
    assert (
        rf["type"] == "json_schema"
        and rf["json_schema"]["strict"] is True
        and rf["json_schema"]["schema"]["additionalProperties"] is False
    )
    assert req["body"]["temperature"] == 0 and req["body"]["seed"] == 42  # deterministic judging


async def test_anthropic_judge_uses_a_forced_tool_call_and_no_thinking(h):
    h.an.judge_score = 4
    run_id = h.add_run(["qwen3:8b"], [GEN], judge_mode="single", judge_model=CLAUDE, config={"warmup": False})
    await h.run(run_id)
    (req,) = judge_requests(h.an)
    assert req["body"]["tool_choice"] == {"type": "tool", "name": "record_scores"} and "thinking" not in req["body"]
    sc = scores(h, run_id)["qwen3:8b"]
    assert sc.outcome == "judged" and sc.value == pytest.approx(0.75)
    assert sc.detail["judge_metrics"] and sc.detail["judge_metrics"][0]["eval_count"] is not None


# ---------------------------------------------------------------- mixed cross-model judging
async def test_local_and_enterprise_models_judge_each_other(h):
    run_id = h.add_run(["qwen3:8b", GPT], [GEN], judge_mode="cross_model", config={"warmup": False})
    assert (await h.run(run_id)).status == "completed"
    j = judgements(h, run_id)
    assert [x[0] for x in j["qwen3:8b"]] == [GPT] and [x[0] for x in j[GPT]] == ["qwen3:8b"]  # nobody judged themselves
    assert all(o == "judged" for rows in j.values() for _, o, _ in rows)
    sc = scores(h, run_id)
    assert sc["qwen3:8b"].value == 1.0  # judged by gpt-4o (score 5)
    assert sc[GPT].value == pytest.approx(0.75)  # judged by the local model (fake judge reply 4/4)
    assert all(x.detail["self_judged"] is False for x in sc.values())


@pytest.mark.parametrize("order,expected_unloads", [(["qwen3:8b", GPT], ["qwen3:8b"]), ([GPT, "qwen3:8b"], [])])
async def test_only_local_judges_are_unloaded_between_judge_groups(h, order, expected_unloads):
    run_id = h.add_run(order, [GEN], judge_mode="cross_model", config={"warmup": False})
    await h.run(run_id)
    first_judge = next(i for i, c in enumerate(h.ollama.calls) if c[0] == "chat" and c[4] is not None)
    after = [c[1] for c in h.ollama.calls[first_judge:] if c[0] == "unload"]
    assert after == expected_unloads
    assert len(judge_requests(h.oa)) == 1  # the cloud judge was called exactly once, never unloaded


async def test_three_way_cross_judging_across_two_providers_and_a_local_model(h):
    h.an.judge_score = 3
    run_id = h.add_run(["qwen3:8b", GPT, CLAUDE], [GEN], judge_mode="cross_model", config={"warmup": False})
    assert (await h.run(run_id)).status == "completed"
    j = judgements(h, run_id)
    for author, rows in j.items():
        assert sorted(x[0] for x in rows) == sorted({"qwen3:8b", GPT, CLAUDE} - {author})
    assert len(judge_requests(h.oa)) == 2 and len(judge_requests(h.an)) == 2  # each cloud judge scores the other two
    assert len(h.oa.chat_requests()) == 3 and len(h.an.chat_requests()) == 3  # 1 generation + 2 judgements each


async def test_judging_starts_only_after_all_generation_even_with_cloud_models(h):
    run_id = h.add_run(["qwen3:8b", GPT], [GEN, GEN], judge_mode="cross_model", config={"warmup": False})
    await h.run(run_id)
    gen_oa = [r for r in h.oa.chat_requests() if "response_format" not in r["body"]]
    assert len(gen_oa) == 2 and len(judge_requests(h.oa)) == 2
    first_local_judge = next(i for i, c in enumerate(h.ollama.calls) if len(c) > 4 and c[4] is not None)
    before = h.ollama.calls[:first_local_judge]
    assert first_local_judge >= 2 and all(c[0] == "unload" or c[4] is None for c in before)  # local generation first
    # the cloud model's generation also finished before its own judging: 2 generation requests precede its 2 judge calls
    kinds = ["judge" if "response_format" in (r["body"] or {}) else "gen" for r in h.oa.chat_requests()]
    assert kinds == ["gen", "gen", "judge", "judge"]


# ---------------------------------------------------------------- failing judges
async def test_an_authentication_failure_becomes_error_judgements_without_further_requests(h):
    h.env["OA_KEY"] = "wrong-key"
    run_id = h.add_run(
        ["qwen3:8b", "gemma:test"], [GEN, GEN], judge_mode="single", judge_model=GPT, config={"warmup": False}
    )
    run = await h.run(run_id)
    assert run.status == "completed"  # a judge's provider failing never fails the run
    j = judgements(h, run_id)
    flat = [x for rows in j.values() for x in rows]
    assert len(flat) == 4 and all(o == "error" for _, o, _ in flat)
    assert len(h.oa.chat_requests()) == 1  # one attempt, no retry, and the other three judgements were never sent
    with h.sf() as s:
        errs = [x.detail["error"] for x in repo.list_judgements(s, repo.latest_attempt(s, run_id).id)]
    assert sum("authentication failed earlier in this run" in e for e in errs) == 3
    assert {x.outcome for x in scores(h, run_id).values()} == {"error"}  # excluded from category means, not scored 0


async def test_a_provider_outage_stops_judging_by_that_provider(h):
    h.oa.script.extend([Step(kind="status", status=503)] * 20)
    run_id = h.add_run(
        ["qwen3:8b", "gemma:test"], [GEN, GEN], judge_mode="single", judge_model=GPT, config={"warmup": False}
    )
    assert (await h.run(run_id)).status == "completed"
    assert len(h.oa.chat_requests()) == 3  # 1 attempt + 2 retries for the first judgement, then the circuit opened
    flat = [x for rows in judgements(h, run_id).values() for x in rows]
    assert len(flat) == 4 and all(o == "error" for _, o, _ in flat)


async def test_one_failing_cloud_judge_leaves_the_other_judges_intact(h):
    h.env["OA_KEY"] = "wrong-key"
    run_id = h.add_run(["qwen3:8b", GPT, CLAUDE], [GEN], judge_mode="cross_model", config={"warmup": False})
    assert (await h.run(run_id)).status == "completed"
    j = judgements(h, run_id)
    by = {a: {jm: o for jm, o, _ in rows} for a, rows in j.items()}
    assert by["qwen3:8b"] == {GPT: "error", CLAUDE: "judged"}  # gpt-4o (bad key) failed, claude still judged
    assert by[CLAUDE] == {"qwen3:8b": "judged", GPT: "error"}
    # gpt-4o's own answer: generation failed with its bad key, so it was never judged
    assert GPT not in j
    sc = scores(h, run_id)
    assert sc["qwen3:8b"].outcome == "judged" and sc["qwen3:8b"].detail["judges_used"] == 1
